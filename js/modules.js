const MODULE_ORDER = ['m1','m2','m3','m4','m5','m6'];

/* ── RENDER MODULE PAGE ──────────────────────────────────── */

function colorClass(color) {
  return `c-${color}`;
}

function renderModulePage() {
  const params = new URLSearchParams(window.location.search);
  const id = params.get('id');
  const mod = MODULES[id];
  if (!mod) { window.location.href = 'index.html'; return; }

  document.title = `${mod.title} — LARK`;

  // Render sidebar
  const sidebar = document.getElementById('module-sidebar');
  if (sidebar) {
    sidebar.innerHTML = MODULE_ORDER.map(key => {
      const m = MODULES[key];
      const isActive = key === id;
      return `
        <a href="module?id=${key}" class="sidebar-item ${isActive ? 'active' : ''}" aria-current="${isActive ? 'page' : 'false'}">
          <span class="sidebar-item-icon" aria-hidden="true">${m.icon}</span>
          <span class="sidebar-item-text">
            <span class="sidebar-item-num">Module ${m.num}</span>
            <span class="sidebar-item-title">${m.title}</span>
          </span>
        </a>
      `;
    }).join('');
  }

  // Render header
  const header = document.getElementById('module-header');
  if (header) {
    header.className = `module-header ${colorClass(mod.color)}`;
    header.innerHTML = `
      <div class="module-header-inner">
        <nav class="breadcrumb" aria-label="Breadcrumb">
          <a href="index.html">Home</a>
          <span aria-hidden="true">›</span>
          <span>Module ${mod.num}</span>
        </nav>
        <div class="module-header-body">
          <div class="module-header-icon" aria-hidden="true">${mod.icon}</div>
          <div>
            <div class="module-tag">Module ${mod.num} of 6</div>
            <h1>${mod.title}</h1>
            <p class="module-tagline">${mod.tagline}</p>
            <div class="module-meta">
              <span>${mod.lessons} lessons</span>
              <span>·</span>
              <span>${mod.activities} activities</span>
            </div>
          </div>
        </div>
      </div>
    `;
  }

  // Render content
  const content = document.getElementById('module-content');
  if (content) {
    content.innerHTML = `
      <div class="module-overview">
        <h2>Overview</h2>
        <p>${mod.overview}</p>
      </div>
      ${mod.sections.map((sec, i) => renderSection(sec, i)).join('')}
      ${renderModuleNav(id)}
    `;
  }
}

function renderSection(sec, index) {
  if (sec.type === 'reading') {
    return `
      <div class="module-section reading-section">
        <div class="section-type-label">
          <svg viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><path d="M2 4h12M2 8h12M2 12h7"/></svg>
          Reading
        </div>
        <h2>${sec.title}</h2>
        <p>${sec.content}</p>
      </div>
    `;
  }

  if (sec.type === 'activity') {
    return `
      <div class="module-section activity-section" id="activity-${index}">
        <div class="section-type-label activity-label">
          <svg viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><circle cx="8" cy="8" r="6"/><polyline points="8,5 8,8 10,10"/></svg>
          Activity
        </div>
        <h2>${sec.title}</h2>
        <ol class="step-list">
          ${sec.steps.map((step, si) => `
            <li class="step-item">
              <div class="step-num" aria-hidden="true">${si + 1}</div>
              <div class="step-text">${step}</div>
            </li>
          `).join('')}
        </ol>
        <button class="btn btn-green btn-md mark-done-btn" data-activity="${index}" aria-label="Mark ${sec.title} as complete">
          Mark complete
        </button>
      </div>
    `;
  }
  return '';
}

function renderModuleNav(currentId) {
  const idx = MODULE_ORDER.indexOf(currentId);
  const prev = idx > 0 ? MODULES[MODULE_ORDER[idx - 1]] : null;
  const next = idx < MODULE_ORDER.length - 1 ? MODULES[MODULE_ORDER[idx + 1]] : null;
  return `
    <div class="module-nav-footer">
      ${prev ? `<a href="module?id=${prev.id}" class="btn btn-ghost btn-md module-nav-btn">← ${prev.title}</a>` : '<div></div>'}
      ${next ? `<a href="module?id=${next.id}" class="btn btn-green btn-md module-nav-btn">${next.title} →</a>` : '<a href="index.html" class="btn btn-green btn-md module-nav-btn">Back to home</a>'}
    </div>
  `;
}

/* ── ACTIVITY COMPLETION ─────────────────────────────────── */
const DONE_KEY = 'lark_done';

function getDone() {
  try { return JSON.parse(localStorage.getItem(DONE_KEY)) || {}; } catch { return {}; }
}

function markDone(moduleId, activityIndex) {
  const done = getDone();
  if (!done[moduleId]) done[moduleId] = [];
  if (!done[moduleId].includes(activityIndex)) done[moduleId].push(activityIndex);
  localStorage.setItem(DONE_KEY, JSON.stringify(done));
}

function initActivityButtons() {
  const done = getDone();
  const params = new URLSearchParams(window.location.search);
  const id = params.get('id');

  document.querySelectorAll('.mark-done-btn').forEach(btn => {
    const actIdx = parseInt(btn.dataset.activity);
    const alreadyDone = done[id]?.includes(actIdx);
    if (alreadyDone) {
      btn.textContent = '✓ Completed';
      btn.classList.add('btn-completed');
      btn.disabled = true;
    }
    btn.addEventListener('click', () => {
      markDone(id, actIdx);
      btn.textContent = '✓ Completed';
      btn.classList.add('btn-completed');
      btn.disabled = true;
      showToast('Activity marked complete!');
      updateModuleProgress(id);
    });
  });
  updateModuleProgress(id);
}

function updateModuleProgress(moduleId) {
  const done = getDone();
  const mod = MODULES[moduleId];
  if (!mod) return;
  const total = mod.sections.filter(s => s.type === 'activity').length;
  const completed = (done[moduleId] || []).length;
  const pct = total > 0 ? Math.round((completed / total) * 100) : 0;

  // Update sidebar progress indicator if present
  const progressEl = document.getElementById('module-progress');
  if (progressEl) {
    progressEl.innerHTML = `
      <div class="sidebar-progress-label">${completed} of ${total} activities complete</div>
      <div class="sidebar-progress-bar">
        <div class="sidebar-progress-fill" style="width:${pct}%"></div>
      </div>
    `;
  }
  // Persist for homepage cards
  const allProgress = JSON.parse(localStorage.getItem('lark_progress') || '{}');
  allProgress[moduleId] = pct;
  localStorage.setItem('lark_progress', JSON.stringify(allProgress));
}
